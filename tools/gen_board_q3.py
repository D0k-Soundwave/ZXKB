"""Generate ZXKB's preview drawing of D0k's Keychron Q3 with KAM Wraith caps.

    python tools/gen_board_q3.py

Reads docs/keyboard/keycaps.json (positions, sizes, legends, ISO Enter), docs/keyboard/layout.json (LED number per
key) and tools/wraith_caps.py (cap and legend colours), and writes app/zxkb/src/board_q3.inc. The output is ASCII:
non-ASCII legends (the arrows) are written as \\u escapes.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import wraith_caps  # defines K: id, x, y, w, cap colours, legends, legend colours (no side effects on import)

caps = {k['id']: k for k in json.load(open(os.path.join(ROOT, 'docs', 'keyboard', 'keycaps.json'), encoding='utf-8'))['keys']}
leds = {k['id']: k.get('led') for k in json.load(open(os.path.join(ROOT, 'docs', 'keyboard', 'layout.json'), encoding='utf-8'))['keys']}
colours = {k['i']: k for k in wraith_caps.K}


def rgb(h):
    h = h.lstrip('#')
    return '0x' + h.upper()


def cstr(s):
    out = ''
    for ch in s:
        if ch in '\\"':
            out += '\\' + ch
        elif 32 <= ord(ch) < 127:
            out += ch
        else:
            out += '\\u%04x' % ord(ch)
    return 'L"' + out + '"'


rows = []
for kid, c in caps.items():
    col = colours.get(kid)
    if kid == 'ent':
        top, side, mc, sc = wraith_caps.GREY[0], wraith_caps.GREY[1], wraith_caps.WH, wraith_caps.RD
    elif col:
        top, side, mc, sc = col['c'][0], col['c'][1], col['mc'], col['sc']
    else:  # the knob
        top, side, mc, sc = '#3a4048', '#2a2e34', '#9aa3ad', '#9aa3ad'
    led = leds.get(kid)
    shape = 1 if kid == 'ent' else 2 if kid == 'knob' else 0
    rows.append('    {%d, %d, %d, %d, %d, %d, %s, %s, %s, %s, %s, %s, %s},  // %s' % (
        round(c['x'] * 100), round(c['y'] * 100), round(c['w'] * 100), round(c.get('h', 1) * 100),
        -1 if led is None else led, shape, rgb(top), rgb(side), rgb(mc), rgb(sc),
        cstr(c.get('main', '')), cstr(c.get('sub', '')), cstr(c.get('keyword', '')), kid))

out = os.path.join(ROOT, 'app', 'zxkb', 'src', 'board_q3.inc')
with open(out, 'w', encoding='ascii', newline='\n') as f:
    f.write('// Generated by tools/gen_board_q3.py from docs/keyboard/keycaps.json, docs/keyboard/layout.json and\n')
    f.write('// tools/wraith_caps.py. Do not edit; edit those and run the generator.\n')
    f.write('// x, y, w, h in hundredths of a key; LED (-1 = none); shape (0 key, 1 ISO Enter, 2 knob);\n')
    f.write('// cap top, cap side, main legend colour, sub legend colour; main, sub, BASIC keyword.\n')
    f.write('\n'.join(rows) + '\n')
print(f'{len(rows)} keys -> {out}')
